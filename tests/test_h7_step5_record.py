"""H7m, the record of step 5 (`results/h7/step5-scores.json`; directive #178).

The record is generated by `scripts/h7_step5.py` and committed with the page printed from it. This test is what checks it
(`repo_liquidity.records.OWN_CHECK`): it checks that the record is the one the stage document describes, was made at this
repository's pin and panel from the tracked records as they are now, reads no locked day, re-fits nothing, carries no verdict, and that
the tracked page is what it renders to. It also recomputes every point figure from the parent at the pin and the three tracked
records, with 40 draws (the points do not depend on the draws; the intervals are not compared).
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import unittest
from datetime import date
from pathlib import Path

from repo_liquidity import PARENT_COMMIT, development, panel
from repo_liquidity import goalposts as gp

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "results" / "h7" / "step5-scores.json"
PAGE = ROOT / "docs" / "research" / "h7-step5.md"
KINK = ROOT / "results" / "h7" / "kink.json"
CLEAN = ROOT / "results" / "h7" / "calendar-clean.json"
ACCOUNT = ROOT / "results" / "h7" / "distribution-account.json"
A_IDS = ("B", "V1", "V2", "V3", "V4", "V5", "V6")
C_IDS = ("C", "CV1", "CV2", "CV3", "CV4")
NOT_SCORABLE = ("CV1", "CV2", "CV4")
POINT_FIELDS = ("point", "events", "strata", "dropped")


class RecordTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.kink = json.loads(KINK.read_text(encoding="utf-8"))
        spec = importlib.util.spec_from_file_location("h7_step5_script", ROOT / "scripts" / "h7_step5.py")
        cls.script = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.script)

    def test_it_is_development_evidence_for_the_estimators_in_play(self):
        self.assertEqual(self.record["tier"], "development")
        self.assertEqual(set(self.record["estimators"]), set(A_IDS) | set(C_IDS))
        self.assertEqual({n for n, e in self.record["estimators"].items() if e["status"] == "not scorable"}, set(NOT_SCORABLE))
        self.assertEqual(set(self.record["benchmarks"]), {"R", "S", "R+S"})
        self.assertEqual(self.record["variant_count"]["declared_and_not_run"], ["D", "DV1", "DV2", "DV3", "DV4"])

    def test_it_gives_no_verdict(self):
        text = RECORD.read_text(encoding="utf-8").lower()
        for word in ("supported", "killed", "eligible", "\"pass\"", "\"fail\"", "inconclusive"):
            self.assertNotIn(word, text)
        self.assertIn("never a verdict", self.record["decides_nothing"])

    def test_it_was_made_at_this_pin_and_panel_from_the_tracked_records_as_they_are(self):
        self.assertEqual(self.record["pins"]["parent_commit"], PARENT_COMMIT)
        self.assertEqual(self.record["pins"]["panel_sha256"], panel.load_manifest(4)["sha256"])
        for name, source in self.record["sources"].items():
            path = ROOT / source["path"]
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), source["sha256"], name)
        self.assertEqual(set(self.record["sources"]), {"kink", "calendar_clean", "distribution_account"})

    def test_the_settings_are_the_declared_ones(self):
        s = self.record["settings"]
        self.assertEqual((s["draws"], s["block_length"], s["mme"], s["event_floor"], s["width_limit_points"]), (10000, 10, 0.05, 10, 3.0))
        self.assertEqual((s["lower_level"], s["upper_level"]), (0.05, 0.95))

    def test_it_read_no_locked_day_and_none_after_the_records_window(self):
        w = self.record["window"]
        last = date.fromisoformat(w["last_day"])
        self.assertLessEqual(last, date(2025, 12, 31))
        self.assertFalse(development.is_locked(last))
        self.assertEqual(w["first_day"], "2020-03-17")
        self.assertEqual(w["dropped_unlabelled"], {"no label": 0, "no ratio": 0, "no state": 0})

    def test_each_estimator_serves_the_days_the_earlier_records_do(self):
        clean = json.loads(CLEAN.read_text(encoding="utf-8"))
        for name in C_IDS:
            self.assertEqual(self.record["estimators"][name]["served_days"], clean["estimators"][name]["summary"]["served_days"], name)
        for name in A_IDS:
            self.assertEqual(self.record["estimators"][name]["served_days"],
                             self.kink["summaries"][name]["all_served_days"]["served_days"], name)

    def test_the_variants_that_serve_no_day_are_not_scorable_with_a_reason_and_no_gain(self):
        for name in NOT_SCORABLE:
            e = self.record["estimators"][name]
            self.assertEqual(e["served_days"], 0, name)
            self.assertIn("not re-fitted", e["reason"], name)
            self.assertNotIn("goalpost_3", e, name)
            self.assertNotIn("goalpost_2", e, name)

    def test_goalpost_one_for_a_is_the_restated_record_and_for_c_is_unreadable_and_never_computed(self):
        for name in A_IDS:
            g = self.record["estimators"][name]["goalpost_1"]
            self.assertEqual(g["recorded"], self.kink["summaries"][name]["all_served_days"]["goalpost_1"], name)
        for name in C_IDS:
            self.assertEqual(self.record["estimators"][name]["goalpost_1"],
                             {"reading": "unreadable on development data, read prospectively (Eleonora, 22 Oct, option 6)"}, name)

    def test_every_scored_estimator_has_three_readings_and_goalpost_two_on_every_split_beside_the_pooled_figure(self):
        labels = list(self.record["splits"])
        self.assertEqual(labels[0], "all: all")
        kinds = {self.record["splits"][label]["kind"] for label in labels}
        self.assertEqual(kinds, {"all", "regime", "day_type", "era"})
        for name, e in self.record["estimators"].items():
            if e["status"] != "scored":
                continue
            self.assertEqual(set(e["goalpost_3"]), {"vs_r", "vs_s", "vs_rs"}, name)
            for kind, rows in e["goalpost_3"].items():
                self.assertEqual(list(rows), labels, (name, kind))
            self.assertEqual(list(e["goalpost_2"]), labels, name)
        for name, rows in self.record["benchmarks"].items():
            self.assertEqual(list(rows), labels, name)

    def test_r_s_and_r_plus_s_are_scored_on_the_same_days_as_the_estimators(self):
        pooled = self.record["splits"]["all: all"]
        self.assertEqual(pooled["days"], self.record["window"]["days"])
        self.assertEqual(pooled["events"], self.record["window"]["events"])
        for name in ("B", "C", "CV3"):
            self.assertEqual(self.record["estimators"][name]["goalpost_2"]["all: all"]["days"], pooled["days"], name)

    def test_the_gain_of_an_interval_is_ordered(self):
        for name, e in self.record["estimators"].items():
            if e["status"] != "scored":
                continue
            for kind, rows in e["goalpost_3"].items():
                for label, row in rows.items():
                    self.assertLessEqual(row["lower"], row["upper"], (name, kind, label))
        for name, rows in self.record["benchmarks"].items():
            for label, row in rows.items():
                self.assertLessEqual(row["lower"], row["upper"], (name, label))

    def test_a_split_under_the_event_floor_is_flagged_and_kept(self):
        for label, row in self.record["splits"].items():
            self.assertEqual(row["under_event_floor"], row["events"] < gp.EVENT_FLOOR, label)
        self.assertTrue(any(row["under_event_floor"] for row in self.record["splits"].values()))

    def test_the_point_figures_are_what_the_parent_and_the_tracked_records_give(self):
        again = self.script.build(draws=40)
        self.assertEqual(again["window"], self.record["window"])
        self.assertEqual(again["splits"], self.record["splits"])
        for name, rows in self.record["benchmarks"].items():
            for label, row in rows.items():
                for field in POINT_FIELDS:
                    self.assertAlmostEqual(again["benchmarks"][name][label][field], row[field], places=9, msg=(name, label, field))
        for name, e in self.record["estimators"].items():
            other = again["estimators"][name]
            self.assertEqual(other["status"], e["status"], name)
            if e["status"] != "scored":
                continue
            for kind, rows in e["goalpost_3"].items():
                for label, row in rows.items():
                    for field in POINT_FIELDS:
                        self.assertAlmostEqual(other["goalpost_3"][kind][label][field], row[field], places=9, msg=(name, kind, label, field))
            self.assertEqual(other["goalpost_2"], e["goalpost_2"], name)
            self.assertEqual(other["goalpost_1"], e["goalpost_1"], name)

    def test_the_tracked_page_is_what_the_record_renders_to(self):
        self.assertEqual(PAGE.read_text(encoding="utf-8"), self.script.markdown(self.record))


if __name__ == "__main__":
    unittest.main()
