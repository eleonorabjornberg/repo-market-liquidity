"""H7m, the record of the account of the bank distribution (`results/h7/distribution-account.json`; directive #144).

The record is generated by `scripts/h7_account.py` and committed with the page printed from it. This test is what checks it
(`repo_liquidity.records.OWN_CHECK`): it does not re-run the fits, it checks that the record is the one the stage document
describes, was made at this repository's pin and panel from the tracked records as they are now, read no locked day, serves
each estimator's days as the earlier records do, and that the tracked page is what it renders to.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import unittest
from datetime import date
from pathlib import Path

from repo_model.data import next_business_day

from repo_liquidity import PARENT_COMMIT, development, panel

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "results" / "h7" / "distribution-account.json"
PAGE = ROOT / "docs" / "research" / "h7-distribution-account.md"
CLEAN = ROOT / "results" / "h7" / "calendar-clean.json"
KINK = ROOT / "results" / "h7" / "kink.json"
ALTERNATIVES = ("as_observed", "all_large_domestic", "proportional_to_assets")
GROUPS = ("large_domestic", "small_domestic", "foreign_related")
A_IDS = ("B", "V1", "V2", "V3", "V4", "V5", "V6")
#: The rounding of the per-day columns (four places of a point) gives a sum of rounded terms a tolerance.
TOLERANCE = 3.5e-4


class RecordTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.clean = json.loads(CLEAN.read_text(encoding="utf-8"))
        cls.kink = json.loads(KINK.read_text(encoding="utf-8"))
        spec = importlib.util.spec_from_file_location("h7_account_script", ROOT / "scripts" / "h7_account.py")
        cls.script = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.script)

    def test_it_is_development_evidence_for_the_estimators_of_a_and_c_and_reports_no_d(self):
        self.assertEqual(self.record["tier"], "development")
        want = {"C", "CV1", "CV2", "CV3", "CV4"} | {f"A_{i}" for i in A_IDS} | {f"Ag_{i}" for i in A_IDS}
        self.assertEqual(set(self.record["estimators"]), want)
        self.assertEqual(set(self.record["not_reported"]), {"D", "DV1", "DV2", "DV3", "DV4"})
        self.assertEqual(set(self.record["not_reported"].values()), {"not reported (D dropped under #142)"})
        self.assertEqual(tuple(self.record["alternatives"]), ALTERNATIVES)
        self.assertEqual(tuple(self.record["groups"]), GROUPS)

    def test_it_decides_nothing(self):
        text = RECORD.read_text(encoding="utf-8").lower()
        for word in ("goalpost", "auroc", "verdict"):
            self.assertNotIn(word, text)

    def test_it_was_made_at_this_pin_and_panel(self):
        self.assertEqual(self.record["pins"]["parent_commit"], PARENT_COMMIT)
        self.assertEqual(self.record["pins"]["panel_sha256"], panel.load_manifest(4)["sha256"])

    def test_it_was_made_from_the_tracked_records_as_they_are(self):
        for name, path in (("calendar_clean", CLEAN), ("kink", KINK)):
            self.assertEqual(self.record["sources"][name]["sha256"], hashlib.sha256(path.read_bytes()).hexdigest(), name)
        self.assertEqual(self.record["pins"], {k: self.clean["pins"][k] for k in self.record["pins"]})
        self.assertEqual(self.record["pins"], {k: self.kink["pins"][k] for k in self.record["pins"]})

    def test_it_read_no_locked_day(self):
        end = development.development_end()
        for name, e in self.record["estimators"].items():
            for day in e["daily"]["days"]:
                self.assertFalse(development.is_locked(date.fromisoformat(day)), (name, day))
            if end is not None and e["daily"]["days"]:
                self.assertLessEqual(date.fromisoformat(e["daily"]["days"][-1]), end, name)
        self.assertLessEqual(date.fromisoformat(self.record["last_served_day"]), date.fromisoformat(self.record["window_end"]))

    def test_each_estimator_serves_the_days_the_earlier_records_do(self):
        for name, entry in self.clean["estimators"].items():
            self.assertEqual(self.record["estimators"][name]["summary"]["served_days"], entry["summary"]["served_days"], name)
        for name in A_IDS:
            self.assertEqual(self.record["estimators"][f"A_{name}"]["summary"]["served_days"],
                             self.kink["summaries"][name]["all_served_days"]["served_days"], name)

    def test_the_variants_that_are_not_identified_have_an_empty_account_that_is_listed(self):
        for name in ("CV1", "CV2", "CV4"):
            e = self.record["estimators"][name]
            self.assertEqual(e["summary"]["served_days"], 0, name)
            self.assertEqual(e["summary"]["alternatives"], {}, name)
            self.assertGreater(e["summary"]["missing_days"], 0, name)

    def test_a_served_day_is_at_least_two_business_days_after_its_refit_cutoff(self):
        for name, e in self.record["estimators"].items():
            for day, cutoff in zip(e["daily"]["days"], e["daily"]["cutoff"]):
                self.assertGreaterEqual(date.fromisoformat(day), next_business_day(date.fromisoformat(cutoff), 2), (name, day))

    def test_groups_sum_to_the_aggregate_and_an_interval_holds_the_point(self):
        for name, e in self.record["estimators"].items():
            daily = e["daily"]
            for alt in ALTERNATIVES:
                col = daily[alt]
                for i, aggregate in enumerate(col["aggregate"]):
                    if col["lower"][i] is not None:
                        self.assertLessEqual(col["lower"][i], aggregate + TOLERANCE, (name, alt, i))
                        self.assertGreaterEqual(col["upper"][i], aggregate - TOLERANCE, (name, alt, i))
                if "groups" in col:
                    total = [sum(col["groups"][g][i] for g in GROUPS) for i in range(len(col["aggregate"]))]
                    self.assertTrue(all(abs(t - a) <= TOLERANCE for t, a in zip(total, col["aggregate"])), (name, alt))

    def test_a_as_defined_gives_the_same_figure_under_every_alternative(self):
        for i in A_IDS:
            daily = self.record["estimators"][f"A_{i}"]["daily"]
            for alt in ALTERNATIVES[1:]:
                self.assertEqual(daily[alt], daily[ALTERNATIVES[0]], (i, alt))
                self.assertNotIn("groups", daily[alt])

    def test_the_tracked_page_is_what_the_record_renders_to(self):
        self.assertEqual(PAGE.read_text(encoding="utf-8"), self.script.markdown(self.record))


if __name__ == "__main__":
    unittest.main()
