"""H7m, the record of the account of the bank distribution (`results/h7/distribution-account.json`; directive #144).

The record is generated by `scripts/h7_account.py` and committed with the page printed from it. This test is what checks it
(`repo_liquidity.records.OWN_CHECK`): it does not re-run the fits, it checks that the record is the one the stage document
describes, was made at this repository's pin and panel from the tracked records as they are now, read no locked day, serves
each estimator's days as the earlier records do, and that the tracked page is what it renders to.

Directive #186 (Eleonora's ruling on finding #182, 26 October 2026, option (a)): the record's "A through the group machinery" rows
(`Ag_B`, `Ag_V1` to `Ag_V6`) are withdrawn for the base mismatch, and the record is republished without them. The superseded record
is kept byte for byte under `archive/h7-distribution-account-5b8ee596/`; `WithdrawalTests` proves that every other row and field is
equal to it. Written before the withdrawal: `WithdrawalTests` failed first with `AttributeError: module 'repo_liquidity.h7_account'
has no attribute 'withdraw_group_reading'` and the record tests with `AssertionError` on the set of estimators.

Recorded mutation for the withdrawal (not a leakage or staleness guard, recorded all the same), 26 October 2026, in a disposable
copy: in `withdraw_group_reading`, replace `entry["view"] == GROUP_VIEW` by `entry["view"] != "C"`, so that it also removes A as
defined. `test_withdraw_removes_only_the_group_reading_and_adds_two_fields` fails with `AssertionError: Items in the second set but
not the first: 'A_B'`, and the refusal test with `AssertionError: ValueError not raised`.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import unittest
from datetime import date
from pathlib import Path

from repo_model.data import next_business_day

from repo_liquidity import PARENT_COMMIT, development, h7_account, panel

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "results" / "h7" / "distribution-account.json"
PAGE = ROOT / "docs" / "research" / "h7-distribution-account.md"
CLEAN = ROOT / "results" / "h7" / "calendar-clean.json"
KINK = ROOT / "results" / "h7" / "kink.json"
ALTERNATIVES = ("as_observed", "all_large_domestic", "proportional_to_assets")
GROUPS = ("large_domestic", "small_domestic", "foreign_related")
A_IDS = ("B", "V1", "V2", "V3", "V4", "V5", "V6")
AG_KEYS = tuple(f"Ag_{i}" for i in A_IDS)
SUPERSEDED = ROOT / "archive" / "h7-distribution-account-5b8ee596" / "distribution-account.json"
SUPERSEDED_SHA256 = "5b8ee596d16ccf6277f7174e109746c342bbfad270d10cfd9071fa9a8ebd20e8"
LABEL = "withdrawn: base mismatch (#182)"
#: The rounding of the per-day columns (four places of a point) gives a sum of rounded terms a tolerance.
TOLERANCE = 3.5e-4


class RecordTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.clean = json.loads(CLEAN.read_text(encoding="utf-8"))
        cls.kink = json.loads(KINK.read_text(encoding="utf-8"))
        spec = importlib.util.spec_from_file_location("h7_account_script", ROOT / "scripts" / "h7_account.py")
        cls.script = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.script)

    def test_it_is_development_evidence_for_the_estimators_of_a_and_c_and_reports_no_d(self):
        self.assertEqual(self.record["tier"], "development")
        want = {"C", "CV1", "CV2", "CV3", "CV4"} | {f"A_{i}" for i in A_IDS}
        self.assertEqual(set(self.record["estimators"]), want)
        self.assertEqual(set(self.record["not_reported"]), {"D", "DV1", "DV2", "DV3", "DV4"})
        self.assertEqual(set(self.record["not_reported"].values()), {"not reported (D dropped under #142)"})
        self.assertEqual(tuple(self.record["alternatives"]), ALTERNATIVES)
        self.assertEqual(tuple(self.record["groups"]), GROUPS)

    def test_it_decides_nothing(self):
        text = RECORD.read_text(encoding="utf-8").lower()
        for word in ("goalpost", "auroc", "verdict"):
            self.assertNotIn(word, text)

    def test_it_was_made_at_this_pin_and_panel(self):
        self.assertEqual(self.record["pins"]["parent_commit"], PARENT_COMMIT)
        self.assertEqual(self.record["pins"]["panel_sha256"], panel.load_manifest(4)["sha256"])

    def test_it_was_made_from_the_tracked_records_as_they_are(self):
        for name, path in (("calendar_clean", CLEAN), ("kink", KINK)):
            self.assertEqual(self.record["sources"][name]["sha256"], hashlib.sha256(path.read_bytes()).hexdigest(), name)
        self.assertEqual(self.record["pins"], {k: self.clean["pins"][k] for k in self.record["pins"]})
        self.assertEqual(self.record["pins"], {k: self.kink["pins"][k] for k in self.record["pins"]})

    def test_it_read_no_locked_day(self):
        end = development.development_end()
        for name, e in self.record["estimators"].items():
            for day in e["daily"]["days"]:
                self.assertFalse(development.is_locked(date.fromisoformat(day)), (name, day))
            if end is not None and e["daily"]["days"]:
                self.assertLessEqual(date.fromisoformat(e["daily"]["days"][-1]), end, name)
        self.assertLessEqual(date.fromisoformat(self.record["last_served_day"]), date.fromisoformat(self.record["window_end"]))

    def test_each_estimator_serves_the_days_the_earlier_records_do(self):
        for name, entry in self.clean["estimators"].items():
            self.assertEqual(self.record["estimators"][name]["summary"]["served_days"], entry["summary"]["served_days"], name)
        for name in A_IDS:
            self.assertEqual(self.record["estimators"][f"A_{name}"]["summary"]["served_days"],
                             self.kink["summaries"][name]["all_served_days"]["served_days"], name)

    def test_the_variants_that_are_not_identified_have_an_empty_account_that_is_listed(self):
        for name in ("CV1", "CV2", "CV4"):
            e = self.record["estimators"][name]
            self.assertEqual(e["summary"]["served_days"], 0, name)
            self.assertEqual(e["summary"]["alternatives"], {}, name)
            self.assertGreater(e["summary"]["missing_days"], 0, name)

    def test_a_served_day_is_at_least_two_business_days_after_its_refit_cutoff(self):
        for name, e in self.record["estimators"].items():
            for day, cutoff in zip(e["daily"]["days"], e["daily"]["cutoff"]):
                self.assertGreaterEqual(date.fromisoformat(day), next_business_day(date.fromisoformat(cutoff), 2), (name, day))

    def test_groups_sum_to_the_aggregate_and_an_interval_holds_the_point(self):
        for name, e in self.record["estimators"].items():
            daily = e["daily"]
            for alt in ALTERNATIVES:
                col = daily[alt]
                for i, aggregate in enumerate(col["aggregate"]):
                    if col["lower"][i] is not None:
                        self.assertLessEqual(col["lower"][i], aggregate + TOLERANCE, (name, alt, i))
                        self.assertGreaterEqual(col["upper"][i], aggregate - TOLERANCE, (name, alt, i))
                if "groups" in col:
                    total = [sum(col["groups"][g][i] for g in GROUPS) for i in range(len(col["aggregate"]))]
                    self.assertTrue(all(abs(t - a) <= TOLERANCE for t, a in zip(total, col["aggregate"])), (name, alt))

    def test_a_as_defined_gives_the_same_figure_under_every_alternative(self):
        for i in A_IDS:
            daily = self.record["estimators"][f"A_{i}"]["daily"]
            for alt in ALTERNATIVES[1:]:
                self.assertEqual(daily[alt], daily[ALTERNATIVES[0]], (i, alt))
                self.assertNotIn("groups", daily[alt])

    def test_the_tracked_page_is_what_the_record_renders_to(self):
        self.assertEqual(PAGE.read_text(encoding="utf-8"), self.script.markdown(self.record))


def _diff(a, b, path=""):
    """Every place two parsed JSON values differ: a recursive diff, as a list of paths."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for key in sorted(set(a) | set(b)):
            if key not in a or key not in b:
                out.append(f"{path}/{key}")
            else:
                out += _diff(a[key], b[key], f"{path}/{key}")
        return out
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return [f"{path}[len]"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in _diff(x, y, f"{path}[{i}]")]
    return [] if a == b and type(a) is type(b) else [path]


class WithdrawalTests(unittest.TestCase):
    """The "A through the group machinery" rows are withdrawn (#186, ruling on #182, option (a)): the rows are removed, and the
    record names the superseded one."""

    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.old = json.loads(SUPERSEDED.read_text(encoding="utf-8"))

    def test_the_superseded_record_is_kept_byte_for_byte_and_named(self):
        self.assertEqual(hashlib.sha256(SUPERSEDED.read_bytes()).hexdigest(), SUPERSEDED_SHA256)
        self.assertEqual(self.record["superseded"]["sha256"], SUPERSEDED_SHA256)
        self.assertIn("#182", self.record["superseded"]["reason"])
        self.assertNotEqual(hashlib.sha256(RECORD.read_bytes()).hexdigest(), SUPERSEDED_SHA256)

    def test_the_republished_record_carries_no_live_ag_figure(self):
        self.assertFalse([k for k in self.record["estimators"] if k.startswith("Ag_")])
        self.assertFalse([k for k, e in self.record["estimators"].items() if "group machinery" in e["view"]])
        self.assertEqual(self.record["withdrawn"]["label"], LABEL)
        self.assertEqual(tuple(self.record["withdrawn"]["estimators"]), AG_KEYS)
        self.assertIn("#182", self.record["withdrawn"]["reason"])
        # No number is kept for a withdrawn row: the entry names the rows, and holds only strings.
        self.assertTrue(all(isinstance(v, str) for v in self.record["withdrawn"]["estimators"]))
        self.assertTrue(all(isinstance(v, str) for k, v in self.record["withdrawn"].items() if k != "estimators"))

    def test_every_other_row_and_field_is_the_superseded_records(self):
        self.assertEqual(set(self.old["estimators"]) - set(self.record["estimators"]), set(AG_KEYS))
        self.assertEqual(set(self.record["estimators"]) - set(self.old["estimators"]), set())
        kept_old = {k: v for k, v in self.old["estimators"].items() if k not in AG_KEYS}
        self.assertEqual(_diff(kept_old, self.record["estimators"]), [])
        self.assertEqual(set(self.record) - set(self.old), {"superseded", "withdrawn"})
        old = {k: v for k, v in self.old.items() if k != "estimators"}
        new = {k: v for k, v in self.record.items() if k not in ("estimators", "superseded", "withdrawn")}
        self.assertEqual(_diff(old, new), [])

    def test_the_page_says_the_reading_is_withdrawn_and_why(self):
        page = PAGE.read_text(encoding="utf-8")
        self.assertIn(LABEL, page)
        self.assertIn(SUPERSEDED_SHA256, page)
        self.assertNotIn("Marked reading, for Eleonora", page)
        self.assertNotIn("Ag_", page)

    def _record(self):
        def row(view):
            return {"view": view, "summary": {"served_days": 3}, "daily": {"days": ["2021-01-04"]}}
        return {"note": "n", "readings": {"a_through_groups": "r"}, "first_served_day": "2021-01-04",
                "estimators": {"A_B": row("A as defined"), "Ag_B": row("A through the group machinery"),
                               "Ag_V1": row("A through the group machinery"), "C": row("C")}}

    def test_withdraw_removes_only_the_group_reading_and_adds_two_fields(self):
        record = self._record()
        before = json.dumps(record, sort_keys=True)
        out = h7_account.withdraw_group_reading(record, superseded="abc", reason="why")
        self.assertEqual(json.dumps(record, sort_keys=True), before)  # the input is not changed
        self.assertEqual(set(out["estimators"]), {"A_B", "C"})
        self.assertEqual(out["estimators"]["A_B"], record["estimators"]["A_B"])
        self.assertEqual(out["withdrawn"]["estimators"], ["Ag_B", "Ag_V1"])
        self.assertEqual(out["withdrawn"]["label"], LABEL)
        self.assertEqual(out["superseded"], {"sha256": "abc", "reason": "why"})
        self.assertEqual(_diff({k: v for k, v in out.items() if k not in ("estimators", "withdrawn", "superseded")},
                               {k: v for k, v in record.items() if k != "estimators"}), [])

    def test_withdraw_refuses_a_record_that_is_already_withdrawn_or_has_no_such_rows(self):
        out = h7_account.withdraw_group_reading(self._record(), superseded="abc", reason="why")
        with self.assertRaises(ValueError):
            h7_account.withdraw_group_reading(out, superseded="abc", reason="why")
        bare = self._record()
        del bare["estimators"]["Ag_B"], bare["estimators"]["Ag_V1"]
        with self.assertRaises(ValueError):
            h7_account.withdraw_group_reading(bare, superseded="abc", reason="why")


if __name__ == "__main__":
    unittest.main()
