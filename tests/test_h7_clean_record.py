"""H7m, the record of the calendar-clean run (`results/h7/calendar-clean.json`; directive #147).

The record is generated by `scripts/h7_calendar_clean.py` on Eleonora's Mac (the run is long) and committed back to the pull
request's branch with the page printed from it. This test is what checks it (`repo_liquidity.records.OWN_CHECK`): it does not
re-run the fits, it checks that the record is the one the declaration describes, was made at this repository's pin and panel,
read no locked day, and that the tracked page is what it renders to. Until the record is committed the test is skipped; that
skip means "not produced yet" and is the only reason for one.
"""

from __future__ import annotations

import importlib.util
import json
import unittest
from datetime import date
from pathlib import Path

from repo_liquidity import PARENT_COMMIT, development, panel

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "results" / "h7" / "calendar-clean.json"
PAGE = ROOT / "docs" / "research" / "h7-calendar-clean.md"


class RecordTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not RECORD.is_file():
            raise unittest.SkipTest("results/h7/calendar-clean.json is not produced yet (needs-mac)")
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        spec = importlib.util.spec_from_file_location("h7_calendar_clean", ROOT / "scripts" / "h7_calendar_clean.py")
        cls.script = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.script)

    def test_it_is_development_evidence_with_the_declared_four_variants(self):
        self.assertEqual(self.record["tier"], "development")
        self.assertEqual(self.record["variant_count_added"], 4)
        self.assertEqual(set(self.record["estimators"]), {"C", "D", "CV1", "CV2", "DV1", "DV2"})
        self.assertEqual(set(self.record["comparison"]), {"CV1", "CV2", "DV1", "DV2"})

    def test_it_was_made_at_this_pin_and_panel(self):
        self.assertEqual(self.record["pins"]["parent_commit"], PARENT_COMMIT)
        self.assertEqual(self.record["pins"]["panel_sha256"], panel.load_manifest(1)["sha256"])

    def test_it_read_no_locked_day(self):
        last = date.fromisoformat(self.record["window_end"])
        end = development.development_end()
        if end is not None:
            self.assertLessEqual(last, end)
        self.assertFalse(development.is_locked(last))
        self.assertTrue(all(not development.is_locked(date.fromisoformat(day)) for day in self.record["cutoffs"]))

    def test_every_estimator_ran_the_same_refits_with_the_same_draws(self):
        cutoffs = self.record["cutoffs"]
        for name, entry in self.record["estimators"].items():
            self.assertEqual([r["cutoff"] for r in entry["refits"]], cutoffs, name)
        self.assertGreaterEqual(self.record["settings"]["replications"], 1)

    def test_the_tracked_page_is_what_the_record_renders_to(self):
        self.assertEqual(PAGE.read_text(encoding="utf-8"), self.script.markdown(self.record))


if __name__ == "__main__":
    unittest.main()
