class LockedTierTests(unittest.TestCase):
    """One lockbox, the model repo's (#59, finding #55): no published row is dated in a tier it holds."""

    def test_every_series_is_dated(self):
        self.assertEqual(set(PUBLICATION_COLUMN), set(snapshots.SERIES))

    def test_no_published_row_is_dated_in_a_locked_tier(self):
        """Leakage guard: a snapshot never publishes a row from a day the parent's lockbox holds.

        Recorded mutation (14 October 2026): in `snapshots._unlocked`, the condition
        `development.is_locked(date.fromisoformat(row["announcement_date"]))` changed to `False`. The tracked files are
        not rebuilt by this test, so the rebuild test kills it: `test_a_snapshot_rebuilds_to_its_tracked_digest` fails
        with AssertionError: 'fa35581f...' != '30e9296a...' for `on_rrp_rate`. This test fails once the snapshots are
        rebuilt under the mutation, with AssertionError: True is not false : '2026-09-16' is dated in a locked tier,
        in `on_rrp_rate`.
        """
        for series, column in PUBLICATION_COLUMN.items():
            for row in snapshots.read(series):
                day = date.fromisoformat(row[column][:10])
                self.assertFalse(development.is_locked(day), f"{row[column]!r} is dated in a locked tier, in `{series}`")

    def test_the_rebuild_follows_the_parents_lockbox(self):
        """With the parent's blind tier moved past 2026-09-16 the FOMC row is published again, so the filter reads the
        lockbox rather than a date here. Recorded mutation (14 October 2026): in `snapshots._unlocked`, the lockbox
        call replaced by `date.fromisoformat(row["announcement_date"]) > date(2026, 9, 3)`. This test then fails with
        AssertionError: 31 != 32."""
        with moved_lockbox(date(2026, 12, 1)), tempfile.TemporaryDirectory() as tmp:
            manifest = snapshots.build("on_rrp_rate", pathlib.Path(tmp), repo_commit="a" * 40)
        self.assertEqual(manifest["rows"], 32)
        self.assertEqual(manifest["locked_rows_omitted"], [])

    def test_the_omitted_row_is_named_in_the_manifest(self):
        for series in ("on_rrp_rate", "srf_rate"):
            manifest = snapshots.load_manifest(series)
            self.assertEqual(manifest["locked_rows_omitted"], ["2026-09-16"], series)
            table = ROOT / manifest["source_table"]
            self.assertEqual(manifest["source_table_sha256"], hashlib.sha256(table.read_bytes()).hexdigest())
            self.assertNotEqual(manifest["source_table_sha256"], manifest["sha256"])

    def test_the_superseded_digests_stay_published_with_a_note(self):
        """A published file is never edited or deleted (`docs/decisions/snapshots.md`): the old bytes stay under their
        own name, and the note says what replaced them and why."""
        note = (ROOT / "snapshots" / "SUPERSEDED.md").read_text(encoding="utf-8")
        for series, old in {"on_rrp_rate": "fa35581f43d90ccf1318d78d3b7583bb5541a6fa0f7e52dbb5cf503b49c9686a",
                            "srf_rate": "d4ded3b02729838430e50ca4034e21e93e8338958e0f808a5dcd87ccf9455606"}.items():
            path = ROOT / "snapshots" / series / f"{old}.csv"
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), old)
            self.assertIn(old, note)
            self.assertIn(snapshots.load_manifest(series)["sha256"], note)


class AgencySecuritiesSnapshotTests(unittest.TestCase):
    """The H.4.1 agency-securities series (#30): built from the two tracked first-print extracts, not a rate table."""

    def test_the_series_is_published_and_describes_itself(self):
        manifest = snapshots.load_manifest("agency_securities")
        self.assertEqual(manifest["series"], "agency_securities")
        self.assertEqual(manifest["columns"], list(snapshots.AGENCY_SECURITIES_COLUMNS))
        self.assertEqual(len(manifest["source_pages"]), manifest["rows"])
        self.assertEqual(manifest["source_tables"], [
            "tests/fixtures/snapshots/h41/h41_agency_first_print.csv",
            "tests/fixtures/snapshots/h41/h41_mbs_first_print.csv",
        ])

    def test_each_row_is_agency_debt_plus_mbs_from_the_same_release(self):
        for row in snapshots.read("agency_securities"):
            self.assertEqual(int(row["agency_securities_change_musd"]),
                             int(row["agency_debt_change_musd"]) + int(row["mbs_change_musd"]), row["week_ended"])

    def test_the_mbs_column_is_the_tracked_mbs_extract_unchanged(self):
        """The existing MBS series is not changed (#30, item 4): the snapshot only reads it."""
        from repo_liquidity import h41

        mbs = {r.week_ended.isoformat(): r.change_from_prior_week for r in h41.load_extract(snapshots.H41_MBS_EXTRACT)}
        for row in snapshots.read("agency_securities"):
            self.assertEqual(int(row["mbs_change_musd"]), mbs[row["week_ended"]])

    def test_an_edited_extract_is_refused_by_the_build(self):
        import shutil

        with tempfile.TemporaryDirectory() as tmp:
            copy = pathlib.Path(tmp) / "agency.csv"
            shutil.copy(snapshots.H41_AGENCY_EXTRACT, copy)
            shutil.copy(str(snapshots.H41_AGENCY_EXTRACT) + ".manifest.json", str(copy) + ".manifest.json")
            copy.write_bytes(copy.read_bytes().replace(b"2017-12-27", b"2017-12-20", 1))
            with self.assertRaisesRegex(ValueError, "does not match its manifest"):
                snapshots.build("agency_securities", pathlib.Path(tmp) / "out", repo_commit="a" * 40,
                                agency_extract=copy)


    def test_the_h8_groups_manifest_describes_the_weekly_series(self):
        """#26: the H.8 group first prints are published like the rate tables, as a copy of the tracked extract.

        Recorded mutation (13 October 2026): in `tests/fixtures/snapshots/h8_groups/h8_group_first_print.releases.json`,
        the `sha256` of the release of 2018-01-12 changed to another digest. This test then fails with ValueError:
        h8_group_first_print.csv: the week ending 2018-01-03 names a page for the
        release of 2018-01-12 that the releases record does not list.
        """
        manifest = snapshots.load_manifest("h8_groups")
        self.assertEqual((manifest["rows"], manifest["first_week"], manifest["last_week"], manifest["last_release"]),
                         (452, "2017-12-27", "2026-08-19", "2026-08-28"))
        self.assertEqual(len(manifest["source_pages"]), 452)
        self.assertEqual(manifest["source_table"], "tests/fixtures/snapshots/h8_groups/h8_group_first_print.csv")
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(snapshots.build("h8_groups", pathlib.Path(tmp), repo_commit=manifest["repo_commit"]), manifest)

class ReadTests(unittest.TestCase):
    def test_reading_by_digest_returns_the_rows(self):
        manifest = snapshots.load_manifest("srf_rate")
        rows = snapshots.read("srf_rate", sha256=manifest["sha256"])
        self.assertEqual(rows[0]["announcement_date"], "2021-07-28")
        self.assertEqual(len(rows), manifest["rows"])

    def test_a_digest_that_is_not_the_published_one_is_refused(self):
        with self.assertRaises(ValueError):
            snapshots.read("srf_rate", sha256="0" * 64)

    def test_an_edited_snapshot_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = pathlib.Path(tmp)
            manifest = snapshots.build("srf_rate", out, repo_commit="a" * 40)
            path = out / manifest["path"]
            path.write_bytes(path.read_bytes().replace(b",0.25,", b",0.30,"))
            with self.assertRaises(ValueError):
                snapshots.read("srf_rate", root=out)

    def test_an_unknown_series_is_refused(self):
        with self.assertRaises(ValueError):
            snapshots.load_manifest("iorb")

    def test_a_repo_commit_that_is_not_a_full_hash_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValueError):
                snapshots.build("srf_rate", pathlib.Path(tmp), repo_commit="HEAD")


